/**
 * Preyas as a 24x24 pixel creature for the optional 8-bit look (slice 8A).
 *
 * Original art, drawn for this app: a round blue water dragon with a finned
 * crest, a curling finned tail and two paddle feet. The creature is faceless:
 * nothing on it reads as a feature of its own. A mood is read from the posture
 * only: how high the body sits, where the head points, how the crest is swept,
 * how the tail curves and how the feet are placed.
 *
 * Each mood has two frames; the difference between them is a one-pixel
 * "breath" (the body sinks a little on frame two). PixelSprite swaps them
 * about every 500 ms while the page is visible.
 *
 * Digits are palette indexes (bitPalette.ts): "0" is transparent, "1" the
 * near-black outline, "3" deep water for the body, "4" light water for the
 * belly and feet, "5" aqua for the fins.
 *
 * How each pose looks, in one line:
 * - neutral: Standing tall, crest upright, tail resting low behind him, both feet on the ground.
 * - happy: Whole body lifted, crest tall and swept back, tail curled up in a happy hook.
 * - excited: Body high off the ground, crest at full sweep, tail shooting up into the air.
 * - angry: Head pushed forward and down, crest pressed flat along the back, legs planted wide.
 * - sad: Body sunk almost to the floor, head hanging low, crest wilted, tail limp.
 * - surprised: Head thrown up on a stretched neck, crest standing straight up, tail flicked back.
 * - thinking: Head tilted and turned away, crest swept to one side, one arm pulled up towards the chin.
 * - listening: Head turned towards you and lowered, body leaning in, tail still.
 * - battle: Crest fanned to its widest, legs in a wide battle stance, tail raised stiff behind.
 *
 * To change a pose, follow src/bits/README.md: edit the numbers of one mood in
 * the snippet there, run it, and paste the printed grid back in below.
 */
