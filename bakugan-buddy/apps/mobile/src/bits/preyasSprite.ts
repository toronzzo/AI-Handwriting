/**
 * The 24x24 Preyas sprite: 9 moods, 2 frames each = 18 frames. Frames
 * 0 to 8 are the "breath in" pose of each mood, frames 9 to 17 the
 * "breath out" pose of the same mood (same order as CANONICAL_MOODS).
 */
export const PREYAS_SPRITE: Sprite = {
  w: PREYAS_BITS_SIZE,
  h: PREYAS_BITS_SIZE,
  frames: CANONICAL_MOODS.map((mood) => MOOD_FRAMES[mood][0]).concat(
    CANONICAL_MOODS.map((mood) => MOOD_FRAMES[mood][1]),
  ),
};

/** The two frame numbers of one mood inside PREYAS_SPRITE (breath in, breath out). */
export function moodFrames(mood: string): [number, number] {
  const index = CANONICAL_MOODS.indexOf(mood as BitMood);
  const at = index === -1 ? 0 : index;
  return [at, at + CANONICAL_MOODS.length];
}

